  var LANGS = ["es", "en", "de", "fr"];
  var STORE_KEY = "lululau.lang";

  function getLang() {
    var saved = null;
    try { saved = localStorage.getItem(STORE_KEY); } catch (e) {}
    if (saved && LANGS.indexOf(saved) !== -1) return saved;
    return "es";
  }

  function setLang(lang) {
    if (LANGS.indexOf(lang) === -1) lang = "es";
    try { localStorage.setItem(STORE_KEY, lang); } catch (e) {}
    apply(lang);
  }

  function apply(lang) {
    var dict = DICT[lang] || DICT.es;

    document.documentElement.setAttribute("lang", lang);

    // Text nodes
    var nodes = document.querySelectorAll("[data-i18n]");
    for (var i = 0; i < nodes.length; i++) {
      var key = nodes[i].getAttribute("data-i18n");
      if (dict[key] != null) nodes[i].innerHTML = dict[key];
    }

    // Attribute translations: data-i18n-attr="placeholder:key;aria-label:key"
    var attrNodes = document.querySelectorAll("[data-i18n-attr]");
    for (var j = 0; j < attrNodes.length; j++) {
      var spec = attrNodes[j].getAttribute("data-i18n-attr");
      var pairs = spec.split(";");
      for (var k = 0; k < pairs.length; k++) {
        var bits = pairs[k].split(":");
        if (bits.length === 2 && dict[bits[1]] != null) {
          attrNodes[j].setAttribute(bits[0].trim(), dict[bits[1]].trim());
        }
      }
    }

    // <title> + meta description (per-page override via data-title-key / data-desc-key)
    var titleKey = document.documentElement.getAttribute("data-title-key") || "meta.title";
    var descKey = document.documentElement.getAttribute("data-desc-key") || "meta.desc";
    if (dict[titleKey]) document.title = dict[titleKey];
    var md = document.querySelector('meta[name="description"]');
    if (md && dict[descKey]) md.setAttribute("content", dict[descKey]);

    // Active state on language buttons
    var btns = document.querySelectorAll("[data-lang]");
    for (var m = 0; m < btns.length; m++) {
      var isActive = btns[m].getAttribute("data-lang") === lang;
      btns[m].classList.toggle("is-active", isActive);
      btns[m].setAttribute("aria-pressed", isActive ? "true" : "false");
    }

    // Notify listeners (e.g. contact page rebuilds wa.me / mailto links)
    try {
      document.dispatchEvent(new CustomEvent("lululau:lang", { detail: { lang: lang } }));
    } catch (e) {}
  }

  function init() {
    // Inject testimonials (constant English)
    var tNodes = document.querySelectorAll("[data-testimonial]");
    for (var i = 0; i < tNodes.length; i++) {
      var id = tNodes[i].getAttribute("data-testimonial");
      if (TESTIMONIALS[id]) tNodes[i].textContent = "“" + TESTIMONIALS[id] + "”";
    }

    // Wire language buttons
    var btns = document.querySelectorAll("[data-lang]");
    for (var j = 0; j < btns.length; j++) {
      btns[j].addEventListener("click", function () {
        setLang(this.getAttribute("data-lang"));
      });
    }

    apply(getLang());
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }

  window.LululauI18n = {
    setLang: setLang,
    getLang: getLang,
    t: function (key) { var d = DICT[getLang()] || DICT.es; return d[key]; }
  };
